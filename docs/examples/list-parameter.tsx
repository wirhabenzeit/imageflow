// A list parameter: a timeline of up to eight stops, each with a date, a place and a colour. The user adds,
// reorders, duplicates and removes stops in the element's generated list control; `render` reads them as an array.
import { defineTemplate, mm, p, printFormat, pt, Spread } from 'imageflow';

const format = printFormat({
  label: 'Example · 20 × 20 cm', trim: { width: mm(200), height: mm(200) },
  bleed: { all: mm(3), binding: mm(0) }, safe: { all: mm(12), binding: mm(15) },
  ends: 'inside-covers', pageCount: { min: 2, max: 200, step: 2 }, output: { minimumTextSize: pt(7) },
});

const stops = p.list({
  label: 'Stops',
  // Item fields are ordinary parameters. Each saved item also has a stable `id`, generated by the app.
  item: {
    place: p.string({ label: 'Place', default: '', maxLength: 40 }),
    date: p.date({ label: 'Date', default: '2027-06-01' }),
    colour: p.color({ label: 'Colour', default: '#243b30' }),
  },
  max: 8,
  // A new book starts with one stop; default items without an `id` get one from their position.
  default: [{ place: 'Tromsø' }],
});

export default defineTemplate({
  id: 'example-list-parameter', version: '1.0.0', contract: 1,
  format,
  spreads: ({ spread }) => ({
    timeline: spread({
      label: 'Timeline',
      elements: { timeline: { label: 'Timeline', parameters: { stops } } },
      render: (ctx) => {
        const items = ctx.elements.timeline.params.stops;
        const area = ctx.geometry.page('right', 'safe');
        return <Spread><ctx.Element id="timeline" rect={{ ...area, height: Math.min(area.height, 12 * Math.max(1, items.length)) }}>
          {items.length === 0 && ctx.mode === 'edit' && <p style={{ fontFamily: 'sans-serif' }}>Add stops to the timeline</p>}
          <ol style={{ margin: 0, padding: 0, listStyle: 'none', fontFamily: 'sans-serif', fontSize: '10pt' }}>
            {/* The item's id is a stable React key: it survives reordering. */}
            {items.map((stop) => <li key={stop.id} style={{ borderLeft: '3mm solid ' + stop.colour, paddingLeft: '3mm', marginBottom: '3mm' }}>
              <strong>{stop.place || 'Unnamed stop'}</strong> · {stop.date}
            </li>)}
          </ol>
        </ctx.Element></Spread>;
      },
    }),
  }),
});
