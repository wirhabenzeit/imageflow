import assert from 'node:assert/strict';
import { cp, mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { test } from 'node:test';
import { authoringSnapshot, writeAuthoringSnapshot } from '../desktop/authoring-sdk';
import { bundleTemplate } from '../desktop/project';
import { templateHash } from '../desktop/template-library';
import { extractTemplateArchive, writeTemplateArchive } from '../desktop/template-archive';

test('generated SDK snapshots are portable, versioned, hash-neutral and excluded from runtime imports', async (t) => {
  const work = await realpath(await mkdtemp(join(tmpdir(), 'imageflow-sdk-')));
  t.after(() => rm(work, { recursive: true, force: true }));
  const types = join(work, 'installed'), template = join(work, 'book', 'template');
  await cp(resolve('authoring'), types, { recursive: true });
  await cp(resolve('node_modules/@types/react'), join(types, 'react-runtime'), { recursive: true });
  await cp(resolve('node_modules/csstype'), join(types, 'csstype'), { recursive: true });
  await mkdir(template, { recursive: true });
  await writeFile(join(template, 'index.tsx'), `import React from 'react';
import { defineTemplate, mm, printFormat, Spread } from 'imageflow';
const format = printFormat({ label: 'F', trim: { width: mm(100), height: mm(100) }, bleed: mm(3), safe: mm(5), pageCount: { min: 2, max: 20, step: 2 } });
export default defineTemplate({ id: 'sdk', version: '1', contract: 1, format, spreads: { main: { label: 'Main', render: () => <Spread /> } } });
`);
  const before = await templateHash(template);
  await writeAuthoringSnapshot(template, types);
  assert.equal(await templateHash(template), before);
  const metadata = JSON.parse(await readFile(join(template, '.imageflow-sdk/api.json'), 'utf8'));
  assert.equal(metadata.contract, 1);
  assert.match(metadata.sdk, /^[a-f0-9]{64}$/);
  // Neither React nor ImageFlow needs to be installed beside the generated standalone snapshot.
  const checked = spawnSync(process.execPath, [resolve('node_modules/typescript/bin/tsc'), '-p', join(template, '.imageflow-sdk/tsconfig.json')], { encoding: 'utf8' });
  assert.equal(checked.status, 0, checked.stdout + checked.stderr);
  const file = join(work, 'Template.imageflow-template');
  await writeTemplateArchive(template, file, types);
  const bytes = await readFile(file);
  assert.ok(bytes.includes(Buffer.from('.imageflow-sdk/api.json')), 'exports include portable tooling for external authors');
  await writeTemplateArchive(template, file, types);
  assert.deepEqual(await readFile(file), bytes);
  const exported = join(work, 'exported');
  await extractTemplateArchive(file, exported);
  assert.equal(await templateHash(exported), before);
  await assert.rejects(readFile(join(exported, '.imageflow-sdk/api.json')), /ENOENT/, 'app import discards the sender’s tooling');
  const installed = await readFile(join(types, 'imageflow.d.ts'), 'utf8');
  await writeFile(join(types, 'imageflow.d.ts'), installed + '\n// Next SDK build\n');
  await writeTemplateArchive(template, file, types);
  assert.equal(await templateHash(template), before);
  assert.deepEqual(JSON.parse(await readFile(join(template, '.imageflow-sdk/api.json'), 'utf8')), metadata, 'export never rewrites the source snapshot');
  assert.notEqual(JSON.parse((await authoringSnapshot(types)).get('.imageflow-sdk/api.json')!.toString()).sdk, metadata.sdk);
  await writeFile(join(template, '.imageflow-sdk/runtime.js'), 'export default 1;');
  await writeFile(join(template, 'index.tsx'), "import n from './.imageflow-sdk/runtime.js'; export default n;");
  await assert.rejects(bundleTemplate(join(work, 'book')), /inside \.imageflow-sdk/);
});
